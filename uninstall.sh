#!/usr/bin/env bash
set -e

# Uninstaller for stanza CLI tool

# Default values
PREFIX=""
AUTO_CONFIRM=false
DETECTED_PREFIX=""
CLAUDE_RULE="$HOME/.claude/rules/stanza.md"
# What will be removed, as parallel lists of row labels and paths (set by
# collect_files)
REMOVE_LABELS=()
REMOVE_PATHS=()

# --- Output helpers ----------------------------------------------------------
# The row grammar of `stanza release`: a bold "stanza <command>" header, then
# "  label   content" rows whose label alone carries color. A copy of
# print_header, print_row, print_hint, and print_done in lib/stanza-common,
# which neither installer can source: install.sh runs before the download,
# and uninstall.sh is often downloaded on its own. Both carry this same
# block; keep the three in step (tests/test-install.sh checks them).
LABEL_WIDTH=8
SGR_BOLD='1'
SGR_LABEL='1;38;5;151'    # bold pale green: rows that report a step
SGR_PLAN='1;38;5;110'     # bold light blue: rows that list the plan before the prompt
SGR_WARN='0;33'    # never bold: bold yellow turns bright yellow on white
SGR_HINT='0;36'
SGR_ERROR='0;31'
SGR_DONE='0;32'
NO_COLOR_FLAG=false

# Succeed when fd $1 (default 1) should get color: never under NO_COLOR or
# --no-color, always under a non-zero CLICOLOR_FORCE, otherwise only for a
# terminal other than TERM=dumb
use_color() {
    [[ -z "${NO_COLOR:-}" && "$NO_COLOR_FLAG" != true ]] || return 1
    [[ -z "${CLICOLOR_FORCE:-}" || "$CLICOLOR_FORCE" == 0 ]] || return 0
    [[ "${TERM:-dumb}" != dumb && -t "${1:-1}" ]]
}

# "stanza $1  ($2)", the name in bold
header() {
    local on="" off=""
    if use_color 1; then on="\033[${SGR_BOLD}m" off='\033[0m'; fi
    printf "%bstanza %s%b%s\n" "$on" "$1" "$off" "${2:+  ($2)}"
}

# "  label   content" to fd $3 (default 1), the label in SGR $4 (default
# SGR_LABEL). An empty label continues the row above.
row() {
    local label="$1" content="${2:-}" fd="${3:-1}" on="" off=""
    if [[ -n "$label" ]] && use_color "$fd"; then
        on="\033[${4:-$SGR_LABEL}m" off='\033[0m'
    fi
    printf "  %b%-${LABEL_WIDTH}s%b%s\n" "$on" "$label" "$off" "$content" >&"$fd"
}

warn() { row warn "$1" 2 "$SGR_WARN"; }
hint() { row hint "$1" 2 "$SGR_HINT"; }
error() { row error "$1" 2 "$SGR_ERROR"; }
more() { row "" "$1" 2; }
done_row() { row "done" "$1" 1 "$SGR_DONE"; }
plan_row() { row "$1" "$2" 1 "$SGR_PLAN"; }

# $1 with a leading $HOME shown as ~
tilde() {
    case "$1" in
        "$HOME" | "$HOME"/*) printf '~%s' "${1#"$HOME"}" ;;
        *) printf '%s' "$1" ;;
    esac
}
# --- End of output helpers ---------------------------------------------------

# True when the file opens with the stamp `stanza rules install` writes, so a
# hand-written rule of the same name is never removed, even one that mentions
# the phrase. Mirrors has_rules_marker and RULES_MARKER in lib/stanza-rules,
# which this standalone script cannot source.
is_generated_rule() {
    [[ -f "$1" ]] && head -1 "$1" 2>/dev/null | grep -q "^<!-- generated by stanza "
}

# Show help message
show_help() {
    cat <<EOF
Usage: ./uninstall.sh [OPTIONS]

Uninstall stanza CLI tool

Options:
  --prefix=PATH    Uninstall from custom location
  --system         Uninstall from /usr/local (requires sudo)
  -y, --yes        Skip confirmation prompt
  --no-color       Print without color (also NO_COLOR=1)
  -h, --help       Show this help message

Examples:
  ./uninstall.sh                    # Auto-detect and remove
  sudo ./uninstall.sh --system      # Remove system install
  ./uninstall.sh --prefix=~/tools   # Remove from custom location
EOF
}

# Parse command-line arguments
parse_args() {
    while [[ $# -gt 0 ]]; do
        case "$1" in
            --prefix=*)
                PREFIX="${1#*=}"
                # Expand tilde if present
                PREFIX="${PREFIX/#\~/$HOME}"
                shift
                ;;
            --system)
                PREFIX="/usr/local"
                shift
                ;;
            -y|--yes)
                AUTO_CONFIRM=true
                shift
                ;;
            --no-color)
                NO_COLOR_FLAG=true
                shift
                ;;
            -h|--help)
                show_help
                exit 0
                ;;
            *)
                error "unknown option: $1; nothing was removed"
                hint "uninstall.sh --help lists the options"
                exit 1
                ;;
        esac
    done
}

# Auto-detect installation location
detect_installation() {
    # Check common installation locations in order
    if [[ -f "$HOME/.local/bin/stanza" ]]; then
        DETECTED_PREFIX="$HOME/.local"
        return 0
    elif [[ -f "/usr/local/bin/stanza" ]]; then
        DETECTED_PREFIX="/usr/local"
        return 0
    else
        return 1
    fi
}

# Verify installation exists at specified prefix
verify_installation() {
    local prefix="$1"

    if [[ ! -f "$prefix/bin/stanza" ]]; then
        return 1
    fi

    return 0
}

# Add $2 to the removal list under row label $1 when it exists
add_file() {
    if [[ -e "$2" ]]; then
        REMOVE_LABELS+=("$1")
        REMOVE_PATHS+=("$2")
    fi
}

# Collect the files to remove under prefix $1
collect_files() {
    local prefix="$1"

    add_file bin "$prefix/bin/stanza"
    if [[ -d "$prefix/lib/stanza" ]]; then
        add_file lib "$prefix/lib/stanza"
    fi

    # Shell completions (system and user locations)
    add_file bash "$prefix/share/bash-completion/completions/stanza"
    add_file bash "$HOME/.bash_completion.d/stanza"
    add_file zsh "$prefix/share/zsh/site-functions/_stanza"
    add_file zsh "$HOME/.zsh/completions/_stanza"

    # Claude Code rule, only when stanza generated it
    if is_generated_rule "$CLAUDE_RULE"; then
        add_file rule "$CLAUDE_RULE"
    fi
}

# List files that will be removed
list_files_to_remove() {
    local i

    header uninstall "$(tilde "$PREFIX")"
    for ((i = 0; i < ${#REMOVE_PATHS[@]}; i++)); do
        plan_row "${REMOVE_LABELS[$i]}" "$(tilde "${REMOVE_PATHS[$i]}")"
    done
    if [[ -f "$CLAUDE_RULE" ]] && ! is_generated_rule "$CLAUDE_RULE"; then
        plan_row keep "$(tilde "$CLAUDE_RULE"), not generated by stanza"
    fi
    printf '\n'
}

# Confirm with user
confirm_removal() {
    # read -p shows the question only when it reads from a terminal
    local shown=true

    if [[ "$AUTO_CONFIRM" == "true" ]]; then
        return 0
    fi

    [[ -t 0 ]] || shown=false
    read -p "  Remove these? This cannot be undone. [y/N] " -n 1 -r
    if [[ "$shown" == true ]]; then
        # Enter already ended the line; any other key did not
        [[ -z "$REPLY" ]] || printf '\n'
        printf '\n'
    fi

    if [[ ! $REPLY =~ ^[Yy]$ ]]; then
        row cancel "nothing was removed"
        exit 0
    fi
}

# Remove files
remove_files() {
    local i path removed_count=0

    for ((i = 0; i < ${#REMOVE_PATHS[@]}; i++)); do
        path="${REMOVE_PATHS[$i]}"
        if [[ -d "$path" ]]; then
            rm -rf "$path"
        else
            rm -f "$path"
        fi
        row "${REMOVE_LABELS[$i]}" "$(tilde "$path")"
        removed_count=$((removed_count + 1))
    done

    if [[ $removed_count -gt 0 ]]; then
        done_row "stanza uninstalled; $removed_count items removed"
    else
        warn "no files were removed"
    fi
}

# Main execution
main() {
    local arg
    # Settle color before anything prints, even an error about an argument
    for arg in "$@"; do
        [[ "$arg" != --no-color ]] || NO_COLOR_FLAG=true
    done

    parse_args "$@"

    # Determine installation prefix
    if [[ -n "$PREFIX" ]]; then
        # User specified a prefix
        if ! verify_installation "$PREFIX"; then
            error "stanza is not installed at $(tilde "$PREFIX"); nothing was removed"
            more "no $(tilde "$PREFIX/bin/stanza")"
            hint "pass the --prefix stanza was installed with"
            exit 1
        fi
    else
        # Auto-detect installation
        if ! detect_installation; then
            error "no stanza installation found; nothing was removed"
            more "searched ~/.local/bin/stanza and /usr/local/bin/stanza"
            hint "for a custom location: uninstall.sh --prefix=PATH"
            exit 1
        fi
        PREFIX="$DETECTED_PREFIX"
    fi

    # Check permissions for system installations
    if [[ "$PREFIX" == "/usr/local" ]] && [[ $EUID -ne 0 ]]; then
        error "removing /usr/local needs root; nothing was removed"
        hint "sudo ./uninstall.sh --system"
        exit 1
    fi

    # List files to be removed
    collect_files "$PREFIX"
    list_files_to_remove

    # Confirm with user
    confirm_removal

    # Remove files
    remove_files
}

# Run main function
main "$@"
